  // ---- Math helpers ----------------------------------------------------

  /** Wraps an angle into [-pi, pi). */
  public static double wrapAngle(double a) {
    return a - 2.0 * Math.PI * Math.floor((a + Math.PI) / (2.0 * Math.PI));
  }

  /**
   * Evaluates sum of c[k] * d^i * vr^j. Term order: for i in 0..degree, for j in
   * 0..degree-i (matches poly_terms() in shot_sim.py).
   */
  public static double evalPoly(double[] c, int degree, double d, double vr) {
    double sum = 0;
    int k = 0;
    for (int i = 0; i <= degree; i++) {
      double di = Math.pow(d, i);
      for (int j = 0; j <= degree - i; j++) {
        sum += c[k++] * di * Math.pow(vr, j);
      }
    }
    return sum;
  }

  /**
   * True if (d, vr) is inside the band the polynomials were fitted on. The band
   * edges are linearly interpolated between grid distances. NaN input, d off the
   * grid, or a NaN band edge (no valid shot there) is false.
   */
  public static boolean inDomain(double d, double vr) {
    if (Double.isNaN(d) || Double.isNaN(vr)) {
      return false;
    }
    double[] g = D_GRID_M;
    int n = g.length;
    if (n == 0 || d < g[0] || d > g[n - 1]) {
      return false;
    }
    double lo;
    double hi;
    if (n == 1) {
      lo = VR_MIN_MPS[0];
      hi = VR_MAX_MPS[0];
    } else {
      int i = 0;
      while (i < n - 2 && d > g[i + 1]) {
        i++;
      }
      double f = (d - g[i]) / (g[i + 1] - g[i]);
      lo = VR_MIN_MPS[i] + f * (VR_MIN_MPS[i + 1] - VR_MIN_MPS[i]);
      hi = VR_MAX_MPS[i] + f * (VR_MAX_MPS[i + 1] - VR_MAX_MPS[i]);
    }
    return vr >= lo && vr <= hi; // NaN edges make this false
  }

  /** Flywheel RPM for an exit speed: linear model times the optional correction map. */
  public static double rpmForSpeed(double exitSpeedMps) {
    return exitSpeedMps * RPM_PER_MPS * correctionFactor(exitSpeedMps);
  }

  // Linear interpolation, clamped at the ends. Empty map means 1.
  private static double correctionFactor(double speed) {
    double[] x = RPM_CORRECTION_SPEEDS_MPS;
    double[] y = RPM_CORRECTION_FACTORS;
    int n = Math.min(x.length, y.length);
    if (n == 0) {
      return 1.0;
    }
    if (speed <= x[0]) {
      return y[0];
    }
    if (speed >= x[n - 1]) {
      return y[n - 1];
    }
    int i = 0;
    while (speed > x[i + 1]) {
      i++;
    }
    double f = (speed - x[i]) / (x[i + 1] - x[i]);
    return y[i] + f * (y[i + 1] - y[i]);
  }

  /**
   * Adds the robot's sideways speed to a shot the polynomials computed.
   *
   * <p>Derivation. Let u be the unit vector from shooter to goal and t be u
   * rotated +90 degrees (CCW). The robot's field velocity is v = v_r*u + v_t*t.
   * The polynomials already handle v_r: they assume the ball's velocity relative
   * to the robot lies in the vertical plane along u, with horizontal part
   * h0 = s*cos(theta) and vertical part s*sin(theta). The robot's v_t*t then adds
   * to the ball's ground velocity, so to land the same shot the relative
   * horizontal vector must be
   *
   * <pre>  h = h0*u - v_t*t</pre>
   *
   * so that h + v_t*t = h0*u again. Therefore
   *
   * <pre>
   *   headingOffset = atan2(-v_t, h0)   (turn from u toward -t)
   *   |h|           = hypot(h0, v_t)
   *   theta'        = atan2(s*sin(theta), |h|)
   *   s'            = hypot(s, v_t)     (= hypot(|h|, s*sin(theta)))
   * </pre>
   *
   * The vertical component and the ground-frame velocity are then exactly those
   * of the simulated shot.
   *
   * @param launchDeg polynomial launch angle
   * @param exitSpeedMps polynomial exit speed
   * @param tangentialVelMps robot speed along t (CCW of the line to the goal)
   */
  public static Compensation compensate(
      double launchDeg, double exitSpeedMps, double tangentialVelMps) {
    double th = Math.toRadians(launchDeg);
    double h0 = exitSpeedMps * Math.cos(th);
    double vz = exitSpeedMps * Math.sin(th);
    double offset = Math.atan2(-tangentialVelMps, h0);
    double hMag = Math.hypot(h0, tangentialVelMps);
    double newLaunch = Math.toDegrees(Math.atan2(vz, hMag));
    double newSpeed = Math.hypot(exitSpeedMps, tangentialVelMps);
    return new Compensation(newLaunch, newSpeed, offset);
  }

  // ---- Solver ----------------------------------------------------------

  /**
   * Solves one shot.
   *
   * <p>The pose is moved forward by the mechanism delay. Then two passes: the
   * first places the shooter using the predicted heading to find a heading
   * target; the second places it using that target, because the robot will be
   * pointing there when it fires. The second pass is returned.
   *
   * @param pose measured pose
   * @param vx field-frame x velocity
   * @param vy field-frame y velocity
   * @param omega turn rate
   */
  public static Solution solve(Pose pose, double vx, double vy, double omega, Goal goal) {
    Pose pred =
        new Pose(
            pose.x + vx * MECHANISM_DELAY_S,
            pose.y + vy * MECHANISM_DELAY_S,
            pose.heading + omega * MECHANISM_DELAY_S);
    Solution first = solvePass(pred, pred.heading, vx, vy, goal);
    double h = Double.isNaN(first.headingTargetRad) ? pred.heading : first.headingTargetRad;
    return solvePass(pred, h, vx, vy, goal);
  }

  private static Solution solvePass(Pose pred, double heading, double vx, double vy, Goal goal) {
    double sx =
        pred.x
            + Math.cos(heading) * SHOOTER_OFFSET_FORWARD_M
            - Math.sin(heading) * SHOOTER_OFFSET_LEFT_M;
    double sy =
        pred.y
            + Math.sin(heading) * SHOOTER_OFFSET_FORWARD_M
            + Math.cos(heading) * SHOOTER_OFFSET_LEFT_M;
    double dx = goal.x - sx;
    double dy = goal.y - sy;
    double d = Math.hypot(dx, dy);
    double bearing = Math.atan2(dy, dx);
    double ux = d > 1e-9 ? dx / d : 1.0;
    double uy = d > 1e-9 ? dy / d : 0.0;
    double vr = vx * ux + vy * uy;
    double vt = vx * -uy + vy * ux;

    // Angle between (shooter - goal) and the window normal.
    double cosA = -(ux * Math.cos(goal.normalRad) + uy * Math.sin(goal.normalRad));
    double approach = Math.acos(Math.max(-1.0, Math.min(1.0, cosA)));
    boolean approachOk = approach <= Math.toRadians(MAX_APPROACH_ANGLE_DEG);

    double nan = Double.NaN;
    double rawTh = nan;
    double rawS = nan;
    double tof = nan;
    double th = nan;
    double s = nan;
    double headingTarget = nan;
    double hood = nan;
    double rpm = nan;
    Reason reason = approachOk ? Reason.OK : Reason.BAD_APPROACH;

    boolean onGrid =
        D_GRID_M.length > 0 && d >= D_GRID_M[0] && d <= D_GRID_M[D_GRID_M.length - 1];
    if (inDomain(d, vr)) {
      rawTh = evalPoly(HOOD_ANGLE_COEFFS, POLY_DEGREE, d, vr);
      rawS = evalPoly(EXIT_SPEED_COEFFS, POLY_DEGREE, d, vr);
      tof = evalPoly(TOF_COEFFS, POLY_DEGREE, d, vr);
      Compensation c = compensate(rawTh, rawS, vt);
      th = c.launchDeg;
      s = c.speedMps;
      headingTarget = wrapAngle(bearing + c.headingOffsetRad - SHOOTER_MOUNT_YAW_RAD);
      hood = th - HOOD_ANGLE_OFFSET_DEG;
      rpm = rpmForSpeed(s);
      if (reason == Reason.OK && !(th >= LAUNCH_MIN_DEG && th <= LAUNCH_MAX_DEG)) {
        reason = Reason.HOOD_LIMIT;
      }
    } else if (reason == Reason.OK) {
      reason = onGrid ? Reason.OUT_OF_DOMAIN : Reason.OUT_OF_RANGE;
    }
    return new Solution(
        reason, pred, sx, sy, d, vr, vt, bearing, rawTh, rawS, th, s,
        headingTarget, hood, rpm, tof, approach);
  }

  /**
   * Decides whether it is safe to fire. Heading tolerance is the angle that keeps
   * the ball inside the window at this distance, capped, and never negative.
   */
  public static GateResult gate(
      Solution s, double measuredRpm, double hoodAngleDeg, double headingRad, double turnRateRadS) {
    double tol = HEADING_TOLERANCE_MAX_RAD;
    if (s.distanceM > 0) {
      // Seen at an angle, the window looks narrower by cos(approach).
      double halfWidth = Double.isNaN(s.approachAngleRad)
          ? GOAL_HALF_WIDTH_M : GOAL_HALF_WIDTH_M * Math.cos(s.approachAngleRad);
      double room = halfWidth - BALL_RADIUS_M - AIM_MARGIN_M;
      tol = Math.min(tol, Math.atan(room / s.distanceM));
    }
    tol = Math.max(0.0, tol);
    boolean rpmOk = Math.abs(measuredRpm - s.targetRpm) <= RPM_TOLERANCE;
    boolean hoodOk = Math.abs(hoodAngleDeg - s.hoodCommandDeg) <= HOOD_TOLERANCE_DEG;
    boolean headingOk = Math.abs(wrapAngle(headingRad - s.headingTargetRad)) <= tol;
    boolean turnOk = Math.abs(turnRateRadS) <= MAX_FIRE_TURN_RATE_RAD_S;
    return new GateResult(s.valid, rpmOk, hoodOk, headingOk, turnOk, tol);
  }

